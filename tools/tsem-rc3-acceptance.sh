#!/bin/sh
# tsem-rc3-acceptance.sh - RC3 hardware acceptance, phase 1: READ-ONLY.
#
#   sh tsem-rc3-acceptance.sh [--repo DIR]
#   ssh root 'sh -s -- --repo /tmp/glinet-tailscale-exit-manager' < tools/tsem-rc3-acceptance.sh
#
# Reads the router's real state and runs the RC3 code of the repository copy (NOT the installed
# one) with its read-only commands (status, intent-check, selftest, diag). It never installs,
# writes or deletes files, never changes UCI, firewall, NAT, routing, tailscale, services or the
# hardware switch, never applies a guard and never sends packets to other hosts. Before and
# after, the state is snapshotted in components (UCI config, iptables, ip6tables, ip rules, static
# routes, TSEM files, kernel modules; tailscale/RA/DHCP routes as a separate dynamic component) and compared
# per component. Normal runtime noise is normalised away (iptables-save timestamp and packet/byte counters,
# route lifetimes, lsmod use counts); a real change in any static component is a FAIL and the differing
# lines are printed. Secrets are not printed.
#
# ACTIVE tests (guard apply, fail-over, reboot, fw3 reload, leak probes) are NOT part of this
# script. `--active` is refused here; see docs/rc/rc3-activation.md for the separate, explicitly
# approved procedure.
#
# Result: RC3_READ_ONLY_OK means ONLY "the read-only evidence shows no blocker; you may now decide
# whether to approve the active tests". It is NOT proof of leak-freedom.
# Exit code: 0 RC3_READ_ONLY_OK, 1 NEEDS_FIX, 2 INSUFFICIENT_EVIDENCE, 64 usage.
#
# Test hooks: PF_ROOT prefixes file paths (fixtures). All logic is in functions; main runs with
# stdin from /dev/null so nothing can swallow the script when streamed through `sh -s`.

set -u

R=${PF_ROOT:-}
R=${R%/}
REPO=/tmp/glinet-tailscale-exit-manager
PRIMARY_IP=100.64.0.30
SECONDARY_IP=100.64.0.31
EXTNET_NETS="10.30.0.0/24 10.30.1.0/24 10.30.2.0/24"
NP=0 NW=0 NF=0 NS=0 NE=0
FAILS='' ESSL='' WARNL=''

oneline() { tr '\n\r\t' '   ' | sed 's/  */ /g; s/^ //; s/ $//' | cut -c1-400; }
emit() { printf '%-5s %-18s %s\n' "$1" "$2" "$(printf '%s' "$3" | oneline)"; }
sect() { printf '\n== %s\n' "$1"; }
pass() { NP=$((NP + 1)); emit PASS "$1" "$2"; }
info() { emit INFO "$1" "$2"; }
warn() { NW=$((NW + 1)); WARNL="$WARNL $1"; emit WARN "$1" "$2"; }
fail() { NF=$((NF + 1)); FAILS="$FAILS
  $1: $2"; emit FAIL "$1" "$2"; }
skipe() { NS=$((NS + 1)); NE=$((NE + 1)); ESSL="$ESSL
  $1: $2"; emit SKIP "$1" "$2 (evidence missing)"; }

have() { command -v "$1" >/dev/null 2>&1; }

# ---- read-only proof: component snapshots (no temp files; everything stays in shell variables) ----
TAB=$(printf '\t')
COMPS="uci tsem-files iptables ip6tables ip-rules routes-static routes-dynamic modules"

# iptables-save without volatile parts: "# Generated by ... on <date>" comment lines and packet/byte counters.
norm_ipt() {
	sed -e '/^#/d' -e 's/^\(:[^ ]* [^ ]*\) \[[0-9]*:[0-9]*\]$/\1 [0:0]/' -e 's/^\[[0-9]*:[0-9]*\] //'
}
# routes without lifetimes. Dynamic = tailscale (table 52, dev tailscale0) and routes learned from RA/DHCP.
norm_routes() { sed -e 's/ expires [^ ]*//' -e 's/ lft [^ ]*//' -e 's/ ageing [^ ]*//'; }
all_routes() { { ip route show table all 2>/dev/null | sed 's/^/v4 /'; ip -6 route show table all 2>/dev/null | sed 's/^/v6 /'; } | norm_routes; }
DYN_RE=' table 52( |$)| dev tailscale0( |$)| proto (ra|dhcp|dhcpv6|ipv6ra)( |$)'

comp_uci() { md5sum "$R"/etc/config/* 2>/dev/null; }
comp_tsem_files() {
	md5sum "$R"/etc/tsem/* "$R"/etc/init.d/* "$R"/etc/gl-switch.d/* "$R"/etc/crontabs/* "$R"/usr/sbin/tsem "$R"/usr/lib/tsem/* 2>/dev/null
	for _d in "$R"/etc/rc.d "$R"/etc/gl-switch.d "$R"/etc/tsem "$R"/usr/lib/tsem; do
		[ -d "$_d" ] || continue
		for _f in "$_d"/*; do
			[ -e "$_f" ] || [ -L "$_f" ] || continue
			if [ -L "$_f" ]; then echo "link $_f $(readlink "$_f" 2>/dev/null)"; else echo "file $_f $(ls -ld "$_f" 2>/dev/null | cut -c1-10)"; fi
		done
	done
}
comp_iptables() { iptables-save 2>/dev/null | norm_ipt; }
comp_ip6tables() { ip6tables-save 2>/dev/null | norm_ipt; }
comp_ip_rules() { ip rule show 2>/dev/null | sed 's/^/v4 /'; ip -6 rule show 2>/dev/null | sed 's/^/v6 /'; }
comp_routes_static() { all_routes | grep -v -E "$DYN_RE"; }
comp_routes_dynamic() { all_routes | grep -E "$DYN_RE"; }
comp_modules() { lsmod 2>/dev/null | awk 'NR != 1 { print $1 }' | sort; }

# snapshot: every normalised line, prefixed with "<component><TAB>"
snapshot() {
	for _c in $COMPS; do
		_fn=comp_$(printf '%s' "$_c" | tr '-' '_')
		"$_fn" 2>/dev/null | sed "s/^/$_c$TAB/"
	done
}
snap_hash() { printf '%s\n' "$2" | grep "^$1$TAB" | md5sum | cut -c1-32; }
# snap_diff COMPONENT BEFORE AFTER: lines only in BEFORE ("- ") or only in AFTER ("+ ")
snap_diff() {
	{ printf '%s\n' "$2" | sed "s/^/B$TAB/"; printf '%s\n' "$3" | sed "s/^/A$TAB/"; } |
		awk -F'\t' -v c="$1" '$2 == c { l = $3; for (i = 4; i <= NF; i++) l = l "\t" $i
			if ($1 == "B") { b[l] = 1; ob[++nb] = l } else { a[l] = 1; oa[++na] = l } }
		END { for (i = 1; i <= nb; i++) if (!(ob[i] in a)) print "- " ob[i]
			for (i = 1; i <= na; i++) if (!(oa[i] in b)) print "+ " oa[i] }'
}
show_diff() { # prints at most 12 differing lines
	_n=0
	_f1=1
	while IFS= read -r _l; do
		[ -n "$_l" ] || continue
		_n=$((_n + 1)); _f1=0
		[ "$_n" -le 12 ] && info "readonly.$1.diff" "$_l"
	done
	[ "$_f1" -eq 0 ] || info "readonly.$1.diff" "(no differing line: only repeated or reordered lines differ)"
	[ "$_n" -le 12 ] || info "readonly.$1.diff" "(and $((_n - 12)) more differing lines)"
}

# Run the repository's tsem (read-only subcommands only).
rtsem() {
	_cf=${TSEM_CONF:-$R/etc/tsem/tsem.conf}
	[ -r "$_cf" ] || _cf=$REPO/src/etc/tsem/tsem.conf
	TSEM_LIBDIR=$REPO/src/usr/lib/tsem TSEM_CONF="$_cf" TSEM_STATE_DIR="$R/etc/tsem" \
		TSEM_RUN_DIR="${TSEM_RUN_DIR:-$R/var/run/tsem}" TSEM_SYSLOG=0 sh "$REPO/src/usr/sbin/tsem" "$@" 2>&1
}

kv() { printf '%s\n' "$1" | sed -n "s/^$2=//p" | head -n 1; }

emit_hashes() {
	_alg=''
	have sha256sum && _alg=sha256sum || { have md5sum && _alg=md5sum; }
	[ -n "$_alg" ] || return 0
	echo "# hashalg $_alg"
	for _f in install.sh uninstall.sh src/usr/sbin/tsem src/usr/lib/tsem/common.sh src/usr/lib/tsem/state.sh src/usr/lib/tsem/conf.sh src/usr/lib/tsem/backend_ipt.sh src/etc/init.d/tsem src/etc/tsem/tsem.conf tools/tsem-rc3-acceptance.sh; do
		[ -r "$REPO/$_f" ] && echo "# hash $($_alg "$REPO/$_f" | cut -d' ' -f1) $_f"
	done
}

check_repo() {
	sect "Repository copy (the code under test)"
	emit_hashes
	if [ -r "$REPO/src/usr/sbin/tsem" ] && [ -r "$REPO/src/usr/lib/tsem/common.sh" ]; then
		_v=$(sed -n 's/^TSEM_VERSION=//p' "$REPO/src/usr/lib/tsem/common.sh" | head -n 1)
		case $_v in
		*rc3*) pass repo.version "$_v" ;;
		*) fail repo.version "repository is '$_v', not an RC3 build" ;;
		esac
		if have sha256sum; then info repo.hash "tsem $(sha256sum "$REPO/src/usr/sbin/tsem" | cut -c1-16) install.sh $(sha256sum "$REPO/install.sh" 2>/dev/null | cut -c1-16)"; fi
	else
		fail repo.present "no repository at $REPO (copy the RC3 checkout there)"
		return 1
	fi
	_ins=$(sed -n 's/^TSEM_VERSION=//p' "$R/usr/lib/tsem/common.sh" 2>/dev/null | head -n 1)
	case $_ins in
	'') info installed.version "none installed" ;;
	*rc3*) info installed.version "RC3 installed ($_ins)" ;;
	*rc2*) info installed.version "RC2 is still installed ($_ins): expected before RC3 activation; this run tests the RC3 repository copy, not the installed RC2" ;;
	*) info installed.version "$_ins installed; this run tests the RC3 repository copy" ;;
	esac
	return 0
}

check_intent() {
	sect "Intent (item 1)"
	_o=$(rtsem intent-check); _rc=$?
	case $_rc in
	0) pass intent "valid: $(printf '%s' "$_o" | sed -n 's/^mode=/mode=/p' | head -n 1)" ;;
	1) warn intent "missing: tsem will treat it as BLOCKED; the installer writes an initial intent" ;;
	*) warn intent "INVALID: $(printf '%s' "$_o" | head -n 1) ; effective state BLOCKED (never DIRECT). Installer keeps it and saves a copy; decide with 'tsem set german|direct'" ;;
	esac
	if [ -e "$R/etc/tsem/intent" ]; then
		info intent.file "$(ls -la "$R/etc/tsem/intent" | oneline) first lines: $(head -n 8 "$R/etc/tsem/intent" 2>/dev/null | tr '\n' '|')"
	fi
}

check_status() {
	sect "Current state (informational before activation)"
	_s=$(rtsem status)
	info state "state=$(kv "$_s" state) guard=$(kv "$_s" guard) leak_risk=$(kv "$_s" leak_risk) intent=$(kv "$_s" intent)/$(kv "$_s" intent_reason) boot_failed=$(kv "$_s" boot_failed)"
	case $(kv "$_s" version) in *rc3*) ;; *) warn status.version "status did not report an RC3 version: $(kv "$_s" version)" ;; esac
	if [ "$(kv "$_s" leak_risk)" = true ]; then info leak_state "leak_risk=true now: EXPECTED while TSEM is not activated (passive install); must be false after activation"; fi
}

check_selftest() {
	sect "Selftest (repository code, read-only)"
	_t=$(rtsem selftest)
	printf '%s\n' "$_t" | while IFS= read -r _l; do
		case $_l in PASS* | WARN* | FAIL*) emit INFO selftest.line "$_l" ;; esac
	done
	_f=$(printf '%s\n' "$_t" | grep -c '^FAIL')
	_w=$(printf '%s\n' "$_t" | grep -c '^WARN')
	[ -n "$_t" ] || { skipe selftest "no output"; return; }
	if [ "$_f" -gt 0 ]; then fail selftest "$_f FAIL line(s) (see above)"; else pass selftest "no FAIL, $_w WARN (WARNs are judged below)"; fi
	printf '%s\n' "$_t" | grep -q '^WARN fastpath' && warn fastpath "fast path present: TSEM removes the module when the guard closes (TSEM_FASTPATH=unload); must be proven in the active test"
	printf '%s\n' "$_t" | grep -q '^WARN dns-resolver.*unspecified' && warn dns.0.0.0.0 "resolver 0.0.0.0 is present; effect UNVERIFIED (see DNS section); active DNS test required"
	printf '%s\n' "$_t" | grep -q 'ip-rule-prohibit' && fail selftest.stale "old ip-rule-prohibit check still reported"
	return 0
}

check_dns() {
	sect "DNS evidence (items 4)"
	for _f in /etc/resolv.conf /tmp/resolv.conf.auto /tmp/resolv.conf.d/resolv.conf.auto; do
		[ -r "$R$_f" ] && info "dns.file" "$_f: $(grep -v '^#' "$R$_f" | head -n 6 | tr '\n' '|')"
	done
	have ip && info dns.route0 "ip route get 0.0.0.0 to $(ip route get 0.0.0.0 2>&1 | head -n 1)"
	have ip && info dns.route127 "ip route get 127.0.0.1 to $(ip route get 127.0.0.1 2>&1 | head -n 1)"
	if have netstat; then info dns.listen "$( (netstat -lnup; netstat -lntp) 2>/dev/null | grep ':53 ' | head -n 4 | tr '\n' '|')"; else skipe dns.listen "netstat missing"; fi
	if have uci; then info dns.dnsmasq "server=$(uci -q get dhcp.@dnsmasq[0].server 2>/dev/null | tr '\n' ' ') noresolv=$(uci -q get dhcp.@dnsmasq[0].noresolv 2>/dev/null) resolvfile=$(uci -q get dhcp.@dnsmasq[0].resolvfile 2>/dev/null)"; fi
	info dns.policy "router DNS leaves via table 52/tunnel in GERMAN; underlay DNS is rejected by TSEM_OUT (TSEM_ALLOW_UNDERLAY_DNS=0); LAN clients: only tunnel/LAN forwarding is allowed. Proven only by the active test."
}

check_controller() {
	sect "Old hardware-switch controller (item 7)"
	_h=$R/etc/gl-switch.d/tailscale-de.sh
	if [ -e "$_h" ]; then
		if grep -q 'tsem' "$_h" 2>/dev/null; then pass hw.controller "hook already calls tsem (single controller)"
		else
			warn hw.controller "old prototype controller present and NOT replaced: it would compete with TSEM. The activation step replaces it with the TSEM hook (original is backed up and restored by uninstall/rollback)"
			info hw.controller.acts "touches: $(grep -oE 'tailscale (set|up)[^;&|]*|iptables[^;&|]*|ip (rule|route)[^;&|]*|uci [a-z]+ [^;&|]*' "$_h" 2>/dev/null | sort -u | head -n 8 | tr '\n' '|')"
			info hw.controller.hash "$(md5sum "$_h" | cut -c1-32)"
		fi
	else
		info hw.controller "no /etc/gl-switch.d/tailscale-de.sh"
	fi
	_other=$(grep -lE 'exit-node|tailscale +set' "$R"/etc/init.d/* "$R"/etc/rc.local "$R"/etc/crontabs/* "$R"/etc/hotplug.d/*/* "$R"/etc/gl-switch.d/* 2>/dev/null | grep -v 'tsem' | grep -v 'tailscale-de.sh' | tr '\n' ' ')
	[ -z "$_other" ] && pass hw.others "no other script sets an exit node" || warn hw.others "other scripts mention exit-node settings: $_other"
	for _d in "$R"/etc/rc.d/S*tsem; do [ -e "$_d" ] && warn hw.autostart "TSEM autostart already enabled: $_d"; done
	return 0
}

check_boot_fw() {
	sect "Boot order and firewall (items 5, 6)"
	if [ -r "$R/etc/init.d/tsem" ]; then
		grep -q '^START=18' "$R/etc/init.d/tsem" && info boot.installed "installed init script START=18 (before firewall 19 / network 20)" || warn boot.installed "installed init script has a different START"
	else info boot.installed "tsem init script not installed"; fi
	if [ -r "$REPO/src/etc/init.d/tsem" ]; then
		grep -q 'boot_guard || true' "$REPO/src/etc/init.d/tsem" && fail boot.silent "repository init script still ignores a failed boot guard" || pass boot.silent "repository init script reports a failed boot guard"
	fi
	_p=$(ls "$R"/etc/rc.d 2>/dev/null | sed -n 's/^S\([0-9][0-9]*\)firewall$/\1/p;s/^S\([0-9][0-9]*\)network$/\1/p' | tr '\n' ' ')
	info boot.rc "firewall/network start priorities: $_p"
	if have uci; then
		_inc=$(uci show firewall 2>/dev/null | grep -c "tsem\|fw-include")
		info fw.include "tsem include entries in /etc/config/firewall: $_inc (0 until activation)"
		_fo=$(uci -q get firewall.@defaults[0].flow_offloading 2>/dev/null); _fh=$(uci -q get firewall.@defaults[0].flow_offloading_hw 2>/dev/null)
		[ "${_fo:-0}" = 1 ] || [ "${_fh:-0}" = 1 ] && warn fw.offload "fw3 flow offloading enabled (flow=${_fo:-0}, hw=${_fh:-0}): established flows bypass FORWARD; TSEM reports it as inconsistent (cannot unload)" || pass fw.offload "fw3 flow offloading not enabled"
	else skipe fw.uci "uci missing"; fi
	info fw.window "no unprotected window is declared solved: boot (START=18 + retry), fw3 reload (include + tick + layer 1) and tailscaled restart are covered by netns tests only; hardware proof = active phase"
}

check_routes() {
	sect "Masquerading and remote-site subnets (item 9)"
	if have iptables-save; then
		_m=$(iptables-save -t nat 2>/dev/null | grep -c 'MASQUERADE')
		[ "$_m" -gt 0 ] && pass masq "$_m MASQUERADE rule(s) present (TSEM never touches them)" || warn masq "no MASQUERADE rule found: tailnet-side NAT must be verified in the active phase"
	else skipe masq "iptables-save missing"; fi
	if have ip; then
		_t=$(ip route show table 52 2>/dev/null)
		for _n in $EXTNET_NETS; do
			printf '%s\n' "$_t" | grep -q "^$_n" && pass "route.$_n" "advertised route in table 52" || warn "route.$_n" "not in table 52 now (needs remote-site subnet routes accepted: tailscale --accept-routes); allowed by TSEM_ALLOW_SUBNETS4"
		done
	else skipe routes "ip missing"; fi
	grep -q 'TSEM_ALLOW_SUBNETS4="10.30.0.0/24 10.30.1.0/24 10.30.2.0/24"' "$R/etc/tsem/tsem.conf" "$REPO/src/etc/tsem/tsem.conf" 2>/dev/null && pass conf.subnets "three remote-site subnets are allowed in tsem.conf" || warn conf.subnets "TSEM_ALLOW_SUBNETS4 does not list the three remote-site subnets"
}

check_nodes() {
	sect "Exit nodes (item 8: Primary to Secondary to BLOCKED, no WAN fallback)"
	if have tailscale; then
		_ts=$(tailscale status 2>/dev/null)
		for _ip in $PRIMARY_IP $SECONDARY_IP; do
			printf '%s\n' "$_ts" | grep -q "^$_ip" && pass "node.$_ip" "present in tailscale status" || warn "node.$_ip" "not listed in tailscale status"
		done
	else skipe nodes "tailscale missing"; fi
	info failover.logic "state machine tested in tests/t_failover.sh (33) and netns: both-down : BLOCKED, never open; return to Primary after TSEM_DWELL and TSEM_RETURN_N stable probes"
}

check_repo_preflight() {
	sect "RC2 preflight (repository tools/tsem-preflight.sh, read-only)"
	if [ -r "$REPO/tools/tsem-preflight.sh" ]; then
		_pf=$(sh "$REPO/tools/tsem-preflight.sh" --repo "$REPO" </dev/null 2>&1); _prc=$?
		printf '%s\n' "$_pf" | grep -E '^(FAIL|WARN) ' | head -n 20 | while IFS= read -r _l; do emit INFO preflight.line "$_l"; done
		info preflight.result "$(printf '%s\n' "$_pf" | grep -E 'RESULT|READY_FOR|NEEDS_FIX|INSUFFICIENT' | tail -n 1) (exit $_prc)"
		[ "$_prc" -eq 1 ] && fail preflight "embedded preflight reports NEEDS_FIX"
		[ "$_prc" -eq 2 ] && skipe preflight "embedded preflight reports insufficient evidence"
	else skipe preflight "tools/tsem-preflight.sh not found"; fi
	return 0
}

# Compare the snapshot taken right before the run (SNAP0) with one taken after it.
# SNAPN (taken 1 s earlier) shows which components change by themselves; for those the run cannot be proven
# harmless, so the result is "insufficient evidence", never a silent pass.
check_readonly() {
	sect "Read-only proof"
	SNAP1=$(snapshot)
	_changed='' _noisy='' _dyn=''
	for _c in $COMPS; do
		_h0=$(snap_hash "$_c" "$SNAP0"); _h1=$(snap_hash "$_c" "$SNAP1"); _hn=$(snap_hash "$_c" "$SNAPN")
		if [ "$_h0" = "$_h1" ]; then
			# md5 of nothing: the tool or the files were not available, so "unchanged" proves nothing
			if [ "$_h1" = d41d8cd98f00b204e9800998ecf8427e ] && [ "$_c" != routes-dynamic ]; then
				if [ "$_c" = ip6tables ]; then info "readonly.$_c" "no data (ip6tables-save missing or no IPv6 rules): nothing to compare"
				else _noisy="$_noisy $_c"; skipe "readonly.$_c" "no data collected (tool or files missing): cannot prove this component unchanged"; fi
			else pass "readonly.$_c" "unchanged ($_h1)"; fi
			continue
		fi
		_d=$(snap_diff "$_c" "$SNAP0" "$SNAP1")
		case $_c in
		routes-dynamic)
			# tailscaled peer routes, RA and DHCP routes come and go by themselves
			info "readonly.$_c" "changed (tailscale/RA/DHCP routes are dynamic; not a configuration change)"
			printf '%s\n' "$_d" | show_diff "$_c"
			if printf '%s\n' "$_d" | grep -E -q "^[-+] v[46] default .*tailscale0|^[-+] v[46] default .* table 52|10\.76\.|$PRIMARY_IP|$SECONDARY_IP"; then
				_noisy="$_noisy $_c"
				skipe "readonly.$_c" "the tailscale default route or an exit-node/remote-site route changed during the run (tailscaled or the installed controller, not this run); rerun to get a clean comparison"
			fi
			continue ;;
		esac
		if [ "$_h0" != "$_hn" ]; then
			_noisy="$_noisy $_c"
			skipe "readonly.$_c" "this component already changed by itself before the run, so the run cannot be proven harmless for it (see diff)"
			printf '%s\n' "$_d" | show_diff "$_c"
			continue
		fi
		_changed="$_changed $_c"
		fail "readonly.$_c" "CHANGED during the run: before $_h0, after $_h1"
		printf '%s\n' "$_d" | show_diff "$_c"
	done
	if [ -n "$_changed" ]; then
		fail readonly "changed components:$_changed (differences above; a concurrent change by another process is possible, rerun once; if the same component changes again, the run is the suspect)"
	elif [ -n "$_noisy" ]; then
		info readonly "no static component changed, but the comparison is inconclusive for:$_noisy (see SKIP lines above)"
	else
		pass readonly "no static component changed during the run ($(printf '%s' "$COMPS" | wc -w | tr -d ' ') components compared; dynamic routes reported separately)"
	fi
}

main() {
	echo "tsem RC3 acceptance, phase 1 (READ-ONLY)  host=$(hostname 2>/dev/null) date=$(date 2>/dev/null)"
	SNAPN=$(snapshot)
	sleep 1
	SNAP0=$(snapshot)
	check_repo && {
		check_intent
		check_status
		check_selftest
		check_dns
		check_controller
		check_boot_fw
		check_routes
		check_nodes
		check_repo_preflight
	}
	check_readonly
	sect "Summary"
	echo "PASS=$NP WARN=$NW FAIL=$NF SKIP(evidence)=$NE"
	[ -n "$WARNL" ] && echo "warnings:$WARNL"
	[ -n "$FAILS" ] && echo "failures:$FAILS"
	[ -n "$ESSL" ] && echo "missing evidence:$ESSL"
	if [ "$NF" -gt 0 ]; then echo "RESULT: NEEDS_FIX"; return 1; fi
	if [ "$NE" -gt 0 ]; then echo "RESULT: INSUFFICIENT_EVIDENCE"; return 2; fi
	echo "RESULT: RC3_READ_ONLY_OK (only: no blocker found by reading; NOT proof of leak-freedom; active tests need separate approval)"
	return 0
}

while [ $# -gt 0 ]; do
	case $1 in
	--repo) [ $# -ge 2 ] || { echo "--repo needs a value" >&2; exit 64; }; REPO=$2; shift 2 ;;
	--active | --active=*) echo "active tests are not part of this script and need separate explicit approval: see docs/rc/rc3-activation.md" >&2; exit 64 ;;
	-h | --help) sed -n '2,24p' "$0"; exit 0 ;;
	*) echo "unknown option: $1" >&2; exit 64 ;;
	esac
done
case $REPO in *[!A-Za-z0-9._/-]*) echo "unsafe --repo value" >&2; exit 64 ;; esac
main </dev/null
exit $?
