'use strict';
// Builds src/www/views/gl-sdk4-ui-tsem.common.js from the shared UI logic and native/tsem-view.js.
//   node tools/build-native-view.js          write the bundle
//   node tools/build-native-view.js --check  exit 1 if the committed bundle differs (drift)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const logic = fs.readFileSync(path.join(root, 'src/www/luci-static/resources/tsem/logic.js'), 'utf8');
const view = fs.readFileSync(path.join(root, 'native/tsem-view.js'), 'utf8');
const raw = '/* GENERATED by tools/build-native-view.js from tsem/logic.js + native/tsem-view.js: do not edit */\n' +
	'(function () {\nvar L = (function () {\n' + logic + '\n})();\n' + view + '\n})()\n';
// ASCII only: umlauts and arrows arrive intact even if the web server sends no charset (seen as "R?ckkehr" on the router)
const out = raw.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const target = path.join(root, 'src/www/views/gl-sdk4-ui-tsem.common.js');
if (process.argv.includes('--check')) {
	const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
	if (cur !== out) { console.error('native bundle is out of date: run node tools/build-native-view.js'); process.exit(1); }
	console.log('native bundle is up to date');
} else {
	fs.mkdirSync(path.dirname(target), { recursive: true });
	fs.writeFileSync(target, out);
	console.log('wrote ' + target + ' (' + out.length + ' bytes)');
}
