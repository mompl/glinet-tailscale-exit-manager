# shellcheck shell=sh
# RC3 acceptance: read-only proof by component snapshots (fake iptables-save / ip / lsmod with realistic noise).

ACC=$ROOT/tools/tsem-rc3-acceptance.sh

# ---- read-only proof: component snapshots (fake iptables-save / ip / lsmod with realistic noise) ----
_ro_setup() {
	t_setup
	sed '/^while \[ \$# -gt 0 \]/,$d' "$ACC" >"$T/acc_lib.sh"
	F=$T/f; RT=$T/rt; FB=$T/fbin
	mkdir -p "$F" "$RT/etc/config" "$RT/etc/tsem" "$RT/etc/rc.d" "$FB"
	printf 'config defaults\n' >"$RT/etc/config/firewall"
	printf 'v=1\nmode=german\n' >"$RT/etc/tsem/intent"
	printf '%s\n' '-A FORWARD -i br-lan -o tailscale0 -j ACCEPT' >"$F/ipt.rules"
	printf '%s\n' '-A FORWARD -i br-lan -j DROP' >"$F/ip6t.rules"
	printf '%s\n' '0: from all lookup local' '5280: from all iif br-lan lookup main suppress_prefixlength 0' '5290: from all iif br-lan prohibit' '32766: from all lookup main' >"$F/rules4"
	printf '%s\n' '0: from all lookup local' '5290: from all iif br-lan prohibit' >"$F/rules6"
	printf '%s\n' 'default via 192.168.8.1 dev eth0 proto static' '192.168.8.0/24 dev br-lan proto kernel scope link src 192.168.8.1' \
		'100.64.0.7 dev tailscale0 table 52' '10.30.0.0/24 dev tailscale0 table 52' >"$F/routes4"
	printf '%s\n' 'fe80::/64 dev br-lan proto kernel metric 256 pref medium' 'default via fe80::1 dev eth0 proto ra metric 1024 pref medium' >"$F/routes6"
	printf '%s\n' nf_conntrack xt_tcpudp >"$F/mods"
	cat >"$FB/iptables-save" <<'FEOF'
#!/bin/sh
n=$(cat "$F/cnt" 2>/dev/null || echo 0); n=$((n + 1)); echo "$n" >"$F/cnt"
echo "# Generated by iptables-save v1.8.7 on Tue Nov 17 09:00:$n 2026"
echo "*filter"; echo ":INPUT ACCEPT [$((n * 7)):$((n * 900))]"; echo ":FORWARD DROP [$n:$((n * 60))]"
cat "$F/ipt.rules" 2>/dev/null
echo COMMIT; echo "# Completed on Tue Nov 17 09:00:$n 2026"
FEOF
	cat >"$FB/ip6tables-save" <<'FEOF'
#!/bin/sh
n=$(cat "$F/cnt" 2>/dev/null || echo 0); n=$((n + 1)); echo "$n" >"$F/cnt"
echo "# Generated by ip6tables-save v1.8.7 on Tue Nov 17 09:00:$n 2026"
echo "*filter"; echo ":FORWARD DROP [$n:$((n * 80))]"
cat "$F/ip6t.rules" 2>/dev/null
echo COMMIT; echo "# Completed on Tue Nov 17 09:00:$n 2026"
FEOF
	cat >"$FB/ip" <<'FEOF'
#!/bin/sh
n=$(cat "$F/cnt" 2>/dev/null || echo 0); n=$((n + 1)); echo "$n" >"$F/cnt"
case "$*" in
"rule show") cat "$F/rules4" ;;
"-6 rule show") cat "$F/rules6" ;;
"route show table all") cat "$F/routes4" ;;
"-6 route show table all") sed "s/\(proto ra.*\)/\1 expires $((2000 - n))sec/" "$F/routes6" ;;
esac
FEOF
	cat >"$FB/lsmod" <<'FEOF'
#!/bin/sh
n=$(cat "$F/cnt" 2>/dev/null || echo 0)
echo "Module                  Size  Used by"
while read -r m; do echo "$m 16384 $((n % 5))"; done <"$F/mods"
FEOF
	chmod +x "$FB"/*
}
_ro_run() { # $1 = mutation function run between the two snapshots
	( PF_ROOT=$RT PATH=$FB:$PATH F=$F; export PF_ROOT PATH F; . "$T/acc_lib.sh"
		SNAPN=$(snapshot); SNAP0=$(snapshot); "$1"; check_readonly; echo "NF=$NF NE=$NE" ) 2>&1
}
_m_none() { :; }

test_readonly_proof_ignores_timestamps_counters_lifetimes_and_use_counts() {
	_ro_setup
	_o=$(_ro_run _m_none)
	assert_contains overall "PASS  readonly " "$_o"
	case $_o in *FAIL*) fail "false positive from runtime noise: $_o" ;; esac
	for _c in uci tsem-files iptables ip6tables ip-rules routes-static routes-dynamic modules; do assert_contains "c-$_c" "PASS  readonly.$_c" "$_o"; done
	assert_contains nf0 "NF=0 NE=0" "$_o"
}

_ro_expect_fail() { # component, mutation function, expected diff fragment
	_ro_setup
	_o=$(_ro_run "$2")
	assert_contains "fail-$1" "FAIL  readonly.$1 " "$_o"
	assert_contains "diff-$1" "$3" "$_o"
	assert_contains "overall-$1" "FAIL  readonly " "$_o"
	for _c in uci tsem-files iptables ip6tables ip-rules routes-static modules; do
		[ "$_c" = "$1" ] || assert_contains "others-$_c" "PASS  readonly.$_c" "$_o"
	done
	case $_o in *"NF=0"*) fail "no failure counted" ;; esac
}
_m_ipt() { echo '-A FORWARD -i br-lan -o eth0 -j ACCEPT' >>"$F/ipt.rules"; }
_m_ip6t() { echo '-A FORWARD -i br-lan -o eth1 -j ACCEPT' >>"$F/ip6t.rules"; }
_m_rule() { sed -i '/5290/d' "$F/rules4"; }
_m_route() { echo 'default via 10.9.9.9 dev eth1 metric 5' >>"$F/routes4"; }
_m_uci() { echo "option disable_ipv6 '0'" >>"$RT/etc/config/firewall"; }
_m_tsem() { ln -s ../init.d/tsem "$RT/etc/rc.d/S18tsem"; }
_m_mod() { echo shortcut_fe >>"$F/mods"; }

test_readonly_proof_fails_on_iptables_change_and_prints_the_rule() { _ro_expect_fail iptables _m_ipt '+ -A FORWARD -i br-lan -o eth0 -j ACCEPT'; }
test_readonly_proof_fails_on_ip6tables_change() { _ro_expect_fail ip6tables _m_ip6t '+ -A FORWARD -i br-lan -o eth1 -j ACCEPT'; }
test_readonly_proof_fails_on_ip_rule_change() { _ro_expect_fail ip-rules _m_rule '5290: from all iif br-lan prohibit'; }
test_readonly_proof_fails_on_static_route_change() { _ro_expect_fail routes-static _m_route '+ v4 default via 10.9.9.9 dev eth1 metric 5'; }
test_readonly_proof_fails_on_uci_change() { _ro_expect_fail uci _m_uci '/etc/config/firewall'; }
test_readonly_proof_fails_on_tsem_file_change() { _ro_expect_fail tsem-files _m_tsem 'S18tsem'; }
test_readonly_proof_fails_on_kernel_module_change() { _ro_expect_fail modules _m_mod '+ shortcut_fe'; }

_m_dyn() { echo '100.64.0.9 dev tailscale0 table 52' >>"$F/routes4"; sed -i '/100.64.0.7/d' "$F/routes4"; }
_m_dyn_default() { echo 'default dev tailscale0 table 52' >>"$F/routes4"; }
_m_ra() { sed -i 's/fe80::1/fe80::2/' "$F/routes6"; }

test_readonly_proof_treats_tailscale_and_ra_route_churn_as_dynamic() {
	_ro_setup; _o=$(_ro_run _m_dyn)
	assert_contains dyn "INFO  readonly.routes-dynamic" "$_o"
	assert_contains peer "100.64.0.9" "$_o"
	assert_contains overall "PASS  readonly " "$_o"
	case $_o in *FAIL*) fail "dynamic route churn must not fail: $_o" ;; esac
	_ro_setup; _o=$(_ro_run _m_ra)
	assert_contains ra "INFO  readonly.routes-dynamic" "$_o"
	case $_o in *FAIL*) fail "RA route churn must not fail: $_o" ;; esac
}

test_readonly_proof_flags_exit_node_default_route_change_as_insufficient_evidence() {
	_ro_setup; _o=$(_ro_run _m_dyn_default)
	assert_contains skip "SKIP  readonly.routes-dynamic" "$_o"
	assert_contains ne1 "NE=1" "$_o"
	case $_o in *"PASS  readonly "*) fail "must not pass overall with an unattributed exit-node route change" ;; esac
	case $_o in *FAIL*) fail "unattributed tailscale change must not be a FAIL: $_o" ;; esac
}

test_readonly_proof_reports_components_that_change_by_themselves_as_insufficient() {
	_ro_setup
	# the rule list differs between every call, i.e. also between the two snapshots taken before the run
	cat >"$FB/ip" <<'FEOF'
#!/bin/sh
n=$(cat "$F/cnt" 2>/dev/null || echo 0); n=$((n + 1)); echo "$n" >"$F/cnt"
case "$*" in
"rule show") echo "0: from all lookup local"; echo "99$n: from all lookup main" ;;
esac
FEOF
	_o=$(_ro_run _m_none)
	assert_contains skip "SKIP  readonly.ip-rules" "$_o"
	case $_o in *"PASS  readonly "*) fail "a self-changing component must not give a clean pass" ;; esac
	case $_o in *"FAIL  readonly.ip-rules"*) fail "self-changing component is not attributable to the run" ;; esac
}

test_readonly_proof_does_not_pass_a_component_without_data() {
	_ro_setup
	printf '#!/bin/sh\n' >"$FB/iptables-save"   # tool present but yields nothing
	_o=$(_ro_run _m_none)
	assert_contains skip "SKIP  readonly.iptables" "$_o"
	case $_o in *"PASS  readonly "*) fail "an empty component must not give a clean overall pass" ;; esac
	assert_contains others "PASS  readonly.uci" "$_o"
}
